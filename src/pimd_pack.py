def _recal(paths, trip_mV=PACK_TRIP_MV):
    """Rebuild SOC_CURVE_MV from session dumps and print it ready to paste.

    Reads the '# pack_v:' comment track pimd_classviz.py writes into every
    session dump.

    Works on discharge RATE rather than on elapsed time, which is what lets it
    take several sessions without stitching them. Each consecutive pair of
    readings gives one rate sample at one voltage; rates are binned by voltage
    and the median of each bin is taken, then minutes-to-trip is the integral
    of 1/rate from the trip upward. A rest between sessions simply contributes
    no sample rather than appearing as capacity from nowhere, and one bad
    reading loses to the median instead of moving the curve.

    Two things are cut rather than fitted:
      * samples after a LOCKOUT mark, because the drive is off past that point
        and the pack drains at roughly half the loaded rate, and
      * rates above MAX_RATE, which are load steps (the first reading of a
        session is taken before the coil starts) rather than discharge.

    Point it at ONE continuous run-down for the sharpest curve; several
    sessions of the same pack also work, blended by the median."""
    import datetime
    import re

    BIN_MV = 200
    MAX_RATE = 200.0        # mV/min above this is a load step, not a discharge

    rates = {}              # bin voltage -> [mV/min]
    used_files = 0
    for path in paths:
        track = []
        try:
            with open(path, errors='replace') as fh:
                for line in fh:
                    if 'LOCKOUT:' in line and line.startswith('# mark:'):
                        break       # drive off past here -- different regime
                    m = re.match(r'# pack_v: ([0-9T:\-.]+), ([0-9.]+), age_s=(\d+)', line)
                    if m:
                        mv = int(round(float(m.group(2)) * 1000))
                        if mv > PACK_ABSENT_MV:
                            track.append((datetime.datetime.fromisoformat(m.group(1)), mv))
        except OSError as exc:
            print('skipping {0}: {1}'.format(path, exc))
            continue
        track.sort()
        if len(track) < 5:
            continue
        used_files += 1
        span = (track[-1][0] - track[0][0]).total_seconds() / 60.0
        print('  {0}: {1} samples, {2:.1f} min, {3:.2f} -> {4:.2f} V'.format(
            path.split('/')[-1], len(track), span,
            track[0][1] / 1000.0, track[-1][1] / 1000.0))
        for (t1, v1), (t2, v2) in zip(track, track[1:]):
            dt = (t2 - t1).total_seconds() / 60.0
            if dt <= 0:
                continue
            rate = (v1 - v2) / dt
            if rate <= 0 or rate > MAX_RATE:
                continue        # recovery, noise, or a load step
            mid = (v1 + v2) / 2.0
            rates.setdefault(int(mid // BIN_MV) * BIN_MV, []).append(rate)

    if not rates:
        print('no usable "# pack_v:" tracks found')
        return 1

    def median(xs):
        xs = sorted(xs)
        n = len(xs)
        return xs[n // 2] if n % 2 else 0.5 * (xs[n // 2 - 1] + xs[n // 2])

    binned = {mv: median(v) for mv, v in rates.items()}
    lo = min(binned)
    hi = max(binned) + BIN_MV
    # Fill gaps by carrying the nearest measured bin, so one missing level
    # cannot cut the curve in half.
    levels = list(range(lo, hi, BIN_MV))
    for mv in levels:
        if mv not in binned:
            near = min(binned, key=lambda k: abs(k - mv))
            binned[mv] = binned[near]

    print('\n  rate by voltage bin (mV/min, median):')
    for mv in sorted(binned, reverse=True):
        print('    {0:5.2f} V  {1:6.1f}  (n={2})'.format(
            mv / 1000.0, binned[mv], len(rates.get(mv, []))))

    # Integrate 1/rate upward from the trip.
    curve = []
    minutes = 0.0
    for mv in sorted(binned):
        if mv + BIN_MV <= trip_mV:
            continue
        top = mv + BIN_MV
        bottom = max(mv, trip_mV)
        minutes += (top - bottom) / binned[mv]
        curve.append((top, minutes))
    curve.append((trip_mV, 0.0))
    curve.sort(key=lambda r: -r[0])

    print('\ntotal pulsing, {0:.2f} V -> {1:.2f} V = {2:.1f} min '
          '(from {3} session(s))'.format(
              curve[0][0] / 1000.0, trip_mV / 1000.0, curve[0][1], used_files))
    print('\nPACK_CAL_EPOCH = {0!r}\n\nSOC_CURVE_MV = ['.format(
        time.strftime('%Y-%m-%d')))
    for i in range(0, len(curve), 4):
        print('    ' + ' '.join('({0:_}, {1:5.1f}),'.format(mv, m)
                                for mv, m in curve[i:i + 4]))
    print(']')
    return 0


def main():
    import argparse
    ap = argparse.ArgumentParser(
        description='PIMD pack fuel gauge. With no arguments, prints the '
                    'current curve as a table for eyeballing.')
    ap.add_argument('--recal', nargs='+', metavar='SESSION_CSV',
                    help='rebuild SOC_CURVE_MV from session dumps and print it')
    args = ap.parse_args()
    if args.recal:
        return _recal(args.recal)
    print('{0}   calibration epoch: {1}'.format(TOOL_VERSION, PACK_CAL_EPOCH))
    print('trip {0:.2f} V   re-arm {1:.2f} V\n'.format(
        PACK_TRIP_MV / 1000.0, PACK_REARM_MV / 1000.0))
    print('  loaded V    SoC %    time left')
    for mv, _ in SOC_CURVE_MV:
        print('   {0:6.2f}     {1:5.1f}      {2}'.format(
            mv / 1000.0, pack_soc_pct(mv), fmt_hm(_minutes_left(mv))))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
